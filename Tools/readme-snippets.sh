#!/bin/sh
# Copies every ```swift block in README.md into Examples/ReadmeSnippets.swift,
# one function per block, so the KadrAudioExamples target compiles the README.
#
#   Tools/readme-snippets.sh          regenerate the file
#   Tools/readme-snippets.sh --check  fail if the file is out of date (CI)
#
# A block that is not Swift you can compile (Package.swift, say) opts out with
# `<!-- readme-snippets: skip -->` on the line before its fence.
#
# Placeholder values the snippets use (a library item, a player, the host's
# `video`) live in Examples/ReadmeSnippetAssets.swift.
#
# Two things differ from kadr's copy of this script, both for the same reason:
#
# - The generated functions sit inside `#if os(iOS) || os(visionOS)`, the guard
#   the library itself uses. MusicLibrary, AudioSession and VoiceoverRecorder do
#   not exist on macOS, so `swift build` compiles none of the snippets. The CI
#   iOS build of the `kadr-audio-Package` scheme is what checks them.
#
# - They are `@MainActor`. The README's snippets are host-app code — a recorder
#   driven from a button, a player paused on an interruption — and
#   VoiceoverRecorder is main-actor isolated, so that is where they run.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
readme="$root/README.md"
out="$root/Examples/ReadmeSnippets.swift"

generate() {
    awk '
    BEGIN {
        print "// Generated by Tools/readme-snippets.sh from README.md. Do not edit:"
        print "// change the README and run the script again."
        print ""
        print "import AVFoundation"
        print "import Foundation"
        print "import Kadr"
        print "import KadrAudio"
        print ""
        print "#if os(iOS) || os(visionOS)"
        n = 0; nlets = 0; inblock = 0; skip = 0; prev = ""
    }
    !inblock && /^```swift[ \t]*$/ {
        inblock = 1
        skip = (prev ~ /<!-- readme-snippets: skip -->/)
        if (!skip) {
            n++
            print ""
            printf "// README.md:%d\n", NR
            print "@MainActor"
            printf "func readmeSnippet%d() async throws {\n", n
        }
        next
    }
    inblock && /^```[ \t]*$/ {
        inblock = 0
        if (!skip) {
            # A snippet ends on `let take = try recorder.stop()` and never reads
            # it. Using each top-level constant keeps the build free of warnings.
            for (i = 1; i <= nlets; i++) printf "    _ = %s\n", lets[i]
            print "}"
        }
        nlets = 0; prev = ""
        next
    }
    inblock {
        if (skip) next
        if ($0 ~ /^import /) next
        if (match($0, /^let [A-Za-z_][A-Za-z0-9_]*/)) lets[++nlets] = substr($0, 5, RLENGTH - 4)
        if ($0 ~ /^[ \t]*$/) print ""; else print "    " $0
        next
    }
    /[^ \t]/ { prev = $0 }
    END {
        if (inblock) { print "unterminated ```swift block in README.md" > "/dev/stderr"; exit 1 }
        print ""
        print "#endif"
    }
    ' "$readme"
}

if [ "${1:-}" = "--check" ]; then
    if ! generate | diff -u "$out" - ; then
        echo "Examples/ReadmeSnippets.swift is out of date. Run Tools/readme-snippets.sh." >&2
        exit 1
    fi
else
    generate > "$out"
fi
